"""Export the r-z black-oil model as an OPM Flow deck and compare Flow results with the built-in simulator.

The deck is a 1 x nr x nz Cartesian grid whose pore volumes (PORV), transmissibilities (TRANY/TRANZ) and
well connection factor (COMPDAT item 8) are written explicitly from the radial geometry, so Flow sees exactly
the same discretisation. Differences that remain by design are listed in DIFFERENCES.
"""
from __future__ import annotations

import io
import math

import numpy as np
import pandas as pd

from .blackoil import BlackOilSim

DIFFERENCES = [
    "Wellbore storage is not modelled in Flow: compare with C = 0.",
    "Flow computes the wellbore hydrostatic head from the flowing mixture; the built-in simulator uses a fixed "
    "oil gradient. Expect a few psi difference in BHP when gas or water enters the well.",
    "Initial saturations come from EQUIL with zero capillary pressure; the built-in model puts residual oil in the "
    "gas cap (Sorg) and in the water leg (Sorw). Gas cap / aquifer volumes differ slightly for that reason.",
    "Rock compaction uses ROCK with the same compressibility, relative to the datum pressure.",
    "The deck has not been run in this environment (OPM Flow is not installed here); treat the first run as a check "
    "of the deck itself.",
]


def _fmt(a, per_line=6):
    out, line = [], []
    for v in a:
        line.append(f"{v:.8g}")
        if len(line) == per_line:
            out.append("  " + " ".join(line)); line = []
    if line:
        out.append("  " + " ".join(line))
    return "\n".join(out)


def _relperm_tables(rp, n=14):
    sw = np.unique(np.concatenate([np.linspace(rp.swc, 1 - rp.sorw, n), [1.0]]))
    krw, _, _ = rp.kr(sw, np.zeros_like(sw))
    krow = np.array([float(rp.kr(s, 0.0)[2]) for s in sw])
    krow[sw >= 1 - rp.sorw - 1e-12] = 0.0
    sg = np.linspace(0.0, 1 - rp.swc, n + 2)
    _, krg, _ = rp.kr(np.full_like(sg, rp.swc), sg)
    krog = np.array([float(rp.kr(rp.swc, g)[2]) for g in sg])
    swof = "\n".join(f"  {a:.6g} {b:.6g} {c:.6g} 0" for a, b, c in zip(sw, krw, krow)) + " /"
    sgof = "\n".join(f"  {a:.6g} {b:.6g} {c:.6g} 0" for a, b, c in zip(sg, krg, krog)) + " /"
    return swof, sgof


def build_deck(sim: BlackOilSim, schedule, t_end_hr: float, title: str = "WTW r-z cross-check") -> str:
    c, v, rp = sim.cfg, sim.pvt, sim.rp
    nr, nz = c.nr, c.nz
    N = nr * nz
    # cell order in Flow: i fastest. Our radial index maps to Flow's J (DY direction), layers to K.
    # Flow cell (I=1, J=r, K=z); linear index = (K-1)*nr + (J-1) with grid 1 x nr x nz -> use I fastest = 1.
    porv = (sim.pv0 / 5.615 * 1.0)                         # rb at p_ref (Flow PORV is at ROCK reference pressure)
    # reorder from n = i*nz + j to Flow order (K outer, J middle, I=1): idx = j*nr + i
    order = np.empty(N, int)
    for i in range(nr):
        for j in range(nz):
            order[j * nr + i] = i * nz + j
    porv_f = porv[order]
    # connections
    tranx = np.zeros(N)          # direction I: trivial (1 cell) -> zeros
    trany = np.zeros(N)          # radial: between J and J+1
    tranz = np.zeros(N)          # vertical: between K and K+1
    for a, b, T in zip(sim.ia, sim.ib, sim.T):
        ia, ja = divmod(int(a), nz)[0], int(a) % nz
        ib, jb = divmod(int(b), nz)[0], int(b) % nz
        if ja == jb:             # radial
            trany[ja * nr + ia] = T
        else:                    # vertical
            tranz[ja * nr + ia] = T
    dz = sim.dz
    perm = np.full(N, 1.0)
    out = io.StringIO()
    w = out.write
    w(f"-- {title}\n-- Generated by Well Test Workbench. Field units.\nRUNSPEC\nTITLE\n  {title}\nDIMENS\n  1 {nr} {nz} /\n"
      "OIL\nGAS\nWATER\nDISGAS\nFIELD\nSTONE2\nTABDIMS\n  1 1 40 40 /\nEQLDIMS\n  1 100 20 /\nWELLDIMS\n  1 "
      f"{nz} 1 1 /\nSTART\n  1 'JAN' 2000 /\n\nGRID\nINIT\n")
    w("DX\n  " + f"{c.re:.6g} " * 0 + f"{N}*1.0 /\nDY\n  {N}*1.0 /\nDZ\n  {N}*{dz:.8g} /\nTOPS\n  {nr}*{c.top_depth:.8g} /\n")
    w("PERMX\n  " + f"{N}*{perm[0]:.6g} /\nPERMY\n  {N}*{perm[0]:.6g} /\nPERMZ\n  {N}*{perm[0]:.6g} /\n")
    w("PORO\n  " + f"{N}*{c.phi:.6g} /\nPORV\n" + _fmt(porv_f) + " /\n")
    w("TRANX\n  " + f"{N}*0 /\nTRANY\n" + _fmt(trany) + " /\nTRANZ\n" + _fmt(tranz) + " /\n")
    w("\nPROPS\n")
    swof, sgof = _relperm_tables(rp)
    w("SWOF\n" + swof + "\nSGOF\n" + sgof + "\n")
    cw = sim.pvt.cw
    w(f"PVTW\n  {v.p_ref:.6g} {v.Bw0:.6g} {cw:.6g} {v.muw:.6g} 0 /\n")
    w(f"ROCK\n  {c.p_datum:.6g} {c.cr:.6g} /\n")
    w(f"DENSITY\n  {v.rho_o_sc:.6g} {v.rho_w_sc:.6g} {0.0764 * sim.pvt_cfg.gas_gravity:.6g} /\n")
    # live oil (Rs in Mscf/stb), dry gas (Bg in rb/Mscf)
    ps = v.p[::6] if len(v.p) > 30 else v.p
    rows = []
    for p_ in ps:
        mu = float(v.muo_sat(p_))
        rows.append(f"  {float(v.rs_sat(p_)) / 1000.0:.8g} {p_:.6g} {float(v.bo_sat(p_)):.6g} {mu:.6g} "
                    f"{v.co:.4g} {float(v.dmu_dp(p_)) / mu:.4g}")
    w("PVCO\n" + ",\n".join(rows) + " /\n")
    w("PVDG\n" + "\n".join(f"  {p_:.6g} {float(v.bg_(p_)) * 1000.0:.8g} {float(v.mug_(p_)):.6g}" for p_ in ps) + " /\n")
    w("\nSOLUTION\n")
    woc = c.woc if c.woc is not None else c.top_depth + c.h + 1000.0
    goc = c.goc if c.goc is not None else c.top_depth - 1000.0
    w(f"EQUIL\n  {sim.D_ref:.6g} {c.p_datum:.6g} {woc:.6g} 0 {goc:.6g} 0 1 1 0 /\n")
    w(f"RSVD\n  {c.top_depth - 1500:.6g} {sim.rs_oil / 1000.0:.8g}\n  {c.top_depth + c.h + 1500:.6g} {sim.rs_oil / 1000.0:.8g} /\n")
    w("\nSUMMARY\nTIME\nWBHP\n  'PROD' /\nWOPR\n  'PROD' /\nWGPR\n  'PROD' /\nWWPR\n  'PROD' /\nWGOR\n  'PROD' /\n"
      "WWCT\n  'PROD' /\nFPR\nFOPT\nFGPT\nFWPT\n")
    w("\nSCHEDULE\n")
    w(f"WELSPECS\n  'PROD' 'G' 1 1 {sim.D_ref:.6g} 'OIL' /\n/\n")
    # connections: our well cells are radial index 0 -> Flow J=1, layers K
    comp = []
    for cell, wi in zip(sim.well_cells, sim.WI):
        j = int(cell) % nz
        comp.append(f"  'PROD' 1 1 {j + 1} {j + 1} 'OPEN' 0 {wi:.8g} {2 * c.rw:.6g} 1* {c.skin * 0:.3g} /")
    w("COMPDAT\n" + "\n".join(comp) + "\n/\n")
    sch = sorted(BlackOilSim._norm_schedule(schedule), key=lambda s: s[0])
    t_prev = 0.0
    events = [(s[0], s) for s in sch]
    bounds = [e[0] for e in events] + [t_end_hr]
    for k, (t0, s) in enumerate(events):
        dt_d = (bounds[k + 1] - t0) / 24.0
        if dt_d <= 0:
            continue
        kind, val = s[1], s[2]
        if kind == "q" and val > 0:
            w(f"WELOPEN\n  'PROD' 'OPEN' /\n/\nWCONPROD\n  'PROD' 'OPEN' 'ORAT' {val:.8g} 4* 14.7 /\n/\n")
        elif kind == "p":
            w(f"WELOPEN\n  'PROD' 'OPEN' /\n/\nWCONPROD\n  'PROD' 'OPEN' 'BHP' 5* {val:.8g} /\n/\n")
        else:
            w("WELOPEN\n  'PROD' 'SHUT' /\n/\n")
        # log-spaced reporting steps inside the period
        n_steps = max(8, int(math.log10(max(dt_d * 24.0, 1.0)) * 8))
        edges = np.geomspace(min(dt_d, 1e-3 / 24.0) if dt_d > 1e-3 / 24.0 else dt_d, dt_d, n_steps)
        steps = np.diff(np.concatenate([[0.0], edges]))
        w("TSTEP\n" + _fmt(steps, 8) + " /\n")
    w("END\n")
    return out.getvalue()


def parse_flow_csv(text: str, time_unit: str = "days"):
    """Read a CSV exported from Flow's summary file (e.g. `ecl2csv summary CASE.UNSMRY -o out.csv`).

    Looks for TIME (days or hours as chosen), WBHP*, WGOR*, WWCT*, WOPR*. Returns arrays in the workbench's
    conventions: time [hr], pwf [psi], GOR [scf/stb], WC [-], qo [stb/d].
    """
    df = pd.read_csv(io.StringIO(text))
    cols = {c.strip().upper(): c for c in df.columns}

    def find(prefix):
        for k, c_ in cols.items():
            if k == prefix or k.startswith(prefix + ":") or k.startswith(prefix + " "):
                return c_
        return None
    tcol = find("TIME")
    if tcol is None:
        raise ValueError("no TIME column found")
    t = pd.to_numeric(df[tcol], errors="coerce").to_numpy(float)
    t_hr = t * 24.0 if time_unit == "days" else t
    out = {"t": t_hr}
    for key, pref, scale in (("pwf", "WBHP", 1.0), ("GOR", "WGOR", 1000.0), ("WC", "WWCT", 1.0), ("qo", "WOPR", 1.0)):
        c_ = find(pref)
        out[key] = pd.to_numeric(df[c_], errors="coerce").to_numpy(float) * scale if c_ else np.full(len(t), np.nan)
    ok = np.isfinite(out["t"])
    return {k: v[ok] for k, v in out.items()}


def compare(res: dict, flow: dict, t_min_hr: float = 0.0):
    """Deviation of Flow from the built-in simulator on Flow's reporting times."""
    t = flow["t"]
    m = (t > t_min_hr) & (t <= res["t"].max())
    out = {}
    pw = np.interp(t[m], res["t"], res["pwf"])
    ok = np.isfinite(flow["pwf"][m])
    out["pwf_rms"] = float(np.sqrt(np.mean((pw[ok] - flow["pwf"][m][ok]) ** 2))) if ok.any() else float("nan")
    out["pwf_max"] = float(np.max(np.abs(pw[ok] - flow["pwf"][m][ok]))) if ok.any() else float("nan")
    flowing = np.interp(t[m], res["t"], np.asarray(res["qset"], float)) > 0
    for key in ("GOR", "WC"):
        a = pd.Series(np.asarray(res[key], float)).ffill().bfill().to_numpy()
        s = np.interp(t[m], res["t"], a)
        f = flow[key][m]
        good = np.isfinite(f) & flowing
        if key == "GOR":
            out["GOR_rel"] = float(np.median(np.abs(s[good] / np.maximum(f[good], 1e-9) - 1))) if good.any() else float("nan")
        else:
            out["WC_abs"] = float(np.max(np.abs(s[good] - f[good]))) if good.any() else float("nan")
    return out
